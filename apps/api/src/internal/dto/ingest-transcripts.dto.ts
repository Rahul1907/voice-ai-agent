import { ApiProperty } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsArray,
  IsDateString,
  IsEnum,
  IsInt,
  IsNotEmpty,
  IsString,
  ValidateNested,
} from 'class-validator';

export class IngestTranscriptSegmentDto {
  @ApiProperty({ description: 'Unique segment UUID generated by worker' })
  @IsString()
  @IsNotEmpty()
  segmentId!: string;

  @ApiProperty({ enum: ['USER', 'AGENT'] })
  @IsEnum(['USER', 'AGENT'], { message: 'role must be USER or AGENT' })
  role!: 'USER' | 'AGENT';

  @ApiProperty({ description: 'Spoken transcript text' })
  @IsString()
  text!: string;

  @ApiProperty({ description: 'Monotonically increasing sequence number' })
  @IsInt()
  sequence!: number;

  @ApiProperty({ description: 'ISO timestamp when text was spoken' })
  @IsDateString()
  spokenAt!: string;
}

export class IngestTranscriptsDto {
  @ApiProperty({ type: [IngestTranscriptSegmentDto] })
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => IngestTranscriptSegmentDto)
  segments!: IngestTranscriptSegmentDto[];
}
